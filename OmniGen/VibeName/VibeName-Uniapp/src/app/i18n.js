export function normalizeLocale(locale) {
  return LOCALES.some((item) => item.id === locale) ? locale : 'en'
}

export function getLocaleDirection(locale) {
  return LOCALES.find((item) => item.id === normalizeLocale(locale))?.dir || 'ltr'
}

export function t(locale, key, values = {}) {
  const normalized = normalizeLocale(locale)
  const template = messages[normalized]?.[key] || messages.en[key] || key
  return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`)
}
